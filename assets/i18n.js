const ORDER = ['ko', 'en', 'ja', 'zh-Hans', 'zh-Hant'];

function detect() {
  const saved = localStorage.getItem('lang');
  if (saved && ORDER.includes(saved)) return saved;
  for (const raw of navigator.languages || [navigator.language || 'en']) {
    const l = String(raw);
    const low = l.toLowerCase();
    if (low.startsWith('ko')) return 'ko';
    if (low.startsWith('ja')) return 'ja';
    if (low.startsWith('zh')) {
      // 앱과 같은 규칙: 스크립트가 명시되면 그대로, 없으면 지역으로 가른다
      if (/hant/i.test(l)) return 'zh-Hant';
      if (/hans/i.test(l)) return 'zh-Hans';
      return /(-|_)(TW|HK|MO)\b/i.test(l) ? 'zh-Hant' : 'zh-Hans';
    }
  }
  return 'en';
}

export const LANG = detect();
const IDX = ORDER.indexOf(LANG);

export function t(key) {
  const v = T[key];
  if (!v) return key;
  // 번체에 없으면 간체로, 그것도 없으면 영어로 — 앱의 3단 폴백과 같다
  return v[IDX] || (IDX === 4 ? v[3] : null) || v[1];
}

export function setLang(l) {
  localStorage.setItem('lang', l);
  location.reload();
}

/** data-t="key" 가 붙은 요소를 전부 번역한다. */
export function applyDom(root = document) {
  root.querySelectorAll('[data-t]').forEach((el) => {
    el.innerHTML = t(el.dataset.t);
  });
  root.querySelectorAll('[data-t-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.tPh);
  });
  document.documentElement.lang = LANG;
}

/** 헤더에 끼워 넣는 언어 선택기. */
export function langPicker() {
  const names = { ko: '한국어', en: 'English', ja: '日本語',
                  'zh-Hans': '简体中文', 'zh-Hant': '繁體中文' };
  const opts = ORDER.map((l) =>
    `<option value="${l}"${l === LANG ? ' selected' : ''}>${names[l]}</option>`).join('');
  return `<select id="langSel" aria-label="Language"
    style="width:auto;padding:5px 8px;font-size:12.5px">${opts}</select>`;
}

export function wireLangPicker() {
  const el = document.getElementById('langSel');
  if (el) el.onchange = () => setLang(el.value);
}

